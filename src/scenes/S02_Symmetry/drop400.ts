// The low-entropy start of the N = 400 run, baked: 400 centres (x0, y0, x1, y1, ...) relative to the drop centre.
// The table is exactly `amorphousDrop(mulberry32(20402), 400)` (below) rounded to 0.01 px — baked so that every
// render tab doesn't pay ~150 ms of packing relaxation. Rounded min centre distance 8.74 px (> 2r + 0.6), max radius
// 112.3 px. Regenerate by running the generator and printing the result if the packing ever needs to change.
/** The low-entropy start: a compact but AMORPHOUS drop (no lattice — the arrow comes from compactness, i.e. few
 * arrangements, not from "order"). Random points are squeezed together while overlaps are resolved; a per-ball
 * exclusion radius drawn from 4.3..5.6 px (polydisperse) keeps the packing from crystallising into hexagonal
 * patches. Centre-to-centre distance >= 2r + 0.6 everywhere. Deterministic (mulberry32(20402)); grid broadphase. */
export function amorphousDrop(rnd: () => number, n: number): Float64Array {
  const x = new Float64Array(n);
  const y = new Float64Array(n);
  const s = new Float64Array(n);
  for (let i = 0; i < n; i++) {
    s[i] = 4.3 + 1.3 * rnd();
    const a = rnd() * Math.PI * 2;
    const rr = Math.sqrt(rnd()) * 140;
    x[i] = rr * Math.cos(a);
    y[i] = rr * Math.sin(a);
  }
  // uniform-grid broadphase (cell >= the largest exclusion distance 2 * 5.6)
  const CELL = 11.5;
  const G = 32; // covers ±184 px
  const head = new Int32Array(G * G);
  const next = new Int32Array(n);
  const cellOf = (v: number) => Math.min(G - 1, Math.max(0, Math.floor(v / CELL) + G / 2));
  const SQUEEZE = 300;
  let maxOv = 1e9;
  for (let it = 0; it < SQUEEZE + 3000; it++) {
    if (it >= SQUEEZE && maxOv < 0.02) break;
    if (it < SQUEEZE) {
      for (let i = 0; i < n; i++) {
        x[i] *= 0.992;
        y[i] *= 0.992;
      }
    }
    head.fill(-1);
    for (let i = 0; i < n; i++) {
      const k = cellOf(y[i]) * G + cellOf(x[i]);
      next[i] = head[k];
      head[k] = i;
    }
    maxOv = 0;
    for (let i = 0; i < n; i++) {
      const cx = cellOf(x[i]);
      const cy = cellOf(y[i]);
      for (let oy = -1; oy <= 1; oy++) {
        const yy = cy + oy;
        if (yy < 0 || yy >= G) continue;
        for (let ox = -1; ox <= 1; ox++) {
          const xx = cx + ox;
          if (xx < 0 || xx >= G) continue;
          for (let j = head[yy * G + xx]; j !== -1; j = next[j]) {
            if (j <= i) continue;
            const D = s[i] + s[j];
            const dx = x[j] - x[i];
            const dy = y[j] - y[i];
            const d2 = dx * dx + dy * dy;
            if (d2 >= D * D) continue;
            const d = Math.sqrt(d2) || 1e-6;
            const ov = D - d;
            if (ov > maxOv) maxOv = ov;
            const nx = dx / d;
            const ny = dy / d;
            x[i] -= nx * ov * 0.5;
            y[i] -= ny * ov * 0.5;
            x[j] += nx * ov * 0.5;
            y[j] += ny * ov * 0.5;
          }
        }
      }
    }
  }
  let mx = 0;
  let my = 0;
  for (let i = 0; i < n; i++) {
    mx += x[i];
    my += y[i];
  }
  mx /= n;
  my /= n;
  const out = new Float64Array(n * 2);
  for (let i = 0; i < n; i++) {
    out[i * 2] = x[i] - mx;
    out[i * 2 + 1] = y[i] - my;
  }
  return out;
}


