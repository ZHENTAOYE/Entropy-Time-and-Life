// Generates src/lib/fonts.css from @fontsource packages, keeping only woff2 sources
// (halves the number of files webpack copies into every bundle).
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const sets = [
  ['noto-serif-sc', ['200', '400', '600', '900']],
  ['noto-sans-sc', ['300', '400', '700']],
  ['jetbrains-mono', ['300', '400', '700']],
  ['cormorant-garamond', ['400', '400-italic', '600', '600-italic']],
];
let out = '/* AUTO-GENERATED by scripts/gen-fonts-css.mjs — do not edit. */\n';
for (const [pkg, weights] of sets) {
  for (const w of weights) {
    const f = path.join(root, 'node_modules/@fontsource', pkg, `${w}.css`);
    let css = fs.readFileSync(f, 'utf8');
    css = css.replace(/,\s*url\([^)]*\.woff\)\s*format\('woff'\)/g, '');
    css = css.replace(/font-display:\s*swap;/g, 'font-display: block;');
    css = css.replace(/url\(\.\/files\//g, `url(../../node_modules/@fontsource/${pkg}/files/`);
    out += `\n/* ${pkg} ${w} */\n` + css;
  }
}
fs.writeFileSync(path.join(root, 'src/lib/fonts.css'), out);
console.log('wrote src/lib/fonts.css', out.length);
